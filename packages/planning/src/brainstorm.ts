import { z, type ZodType } from "zod";

import type {
  BrainstormConfig,
  BrainstormLLM,
  BrainstormLevel,
  BrainstormOutput,
  BrainstormTrigger,
  Recommendation,
  TriggerContext,
  TriggerReason,
} from "./brainstorm-types.js";

export const BrainstormResponseSchema = z.object({
  recommendations: z.array(z.object({
    action: z.enum([
      "create_task", "create_story", "create_feature",
      "reorder", "reopen", "record_insight", "flag_risk",
    ]),
    title: z.string(),
    description: z.string(),
    priority: z.enum(["critical", "high", "medium", "low"]).optional(),
    rationale: z.string(),
    relatedTo: z.string().optional(),
    dependsOn: z.array(z.string()).optional(),
  })).default([]),
  reasoning: z.string(),
  dissent: z.string().optional(),
});

const DEFAULT_CONFIG: BrainstormConfig = {
  tasksPerBrainstorm: 5,
  standardModel: "local",
  highModel: "claude-sonnet-4-6",
  deepModel: "claude-opus-4-8",
};

export class StubBrainstormLLM implements BrainstormLLM {
  readonly calls: string[] = [];

  async generateStructured<T>(prompt: string, schema: ZodType<T>): Promise<T> {
    this.calls.push(prompt);
    return schema.parse({
      recommendations: [
        {
          action: "record_insight",
          title: "Stub insight",
          description: "Generated by stub LLM",
          priority: "medium",
          rationale: "Placeholder for real LLM output",
        },
      ],
      reasoning: `Analyzed context from prompt (${prompt.length} chars)`,
      dissent: prompt.includes("skeptic") ? "Skeptic raises concerns about scope." : undefined,
    });
  }
}

export class BrainstormEngine {
  private readonly config: BrainstormConfig;
  private readonly llm: BrainstormLLM;

  constructor(llm: BrainstormLLM, config?: Partial<BrainstormConfig>) {
    this.config = { ...DEFAULT_CONFIG, ...config };
    this.llm = llm;
  }

  evaluateTrigger(ctx: TriggerContext): BrainstormTrigger | null {
    if (ctx.driftDetected) {
      return this.buildTrigger("direction_drift", "deep", "Direction drift detected — strategic review required");
    }

    const epicCompletion = ctx.recentCompletions.find((c) => c.type === "epic");
    if (epicCompletion) {
      return this.buildTrigger("epic_completed", "deep", `Epic ${epicCompletion.id} completed — major milestone review`, [
        epicCompletion.id,
      ]);
    }

    if (!ctx.hasReadyTasks && ctx.blockedTaskIds.length > 0) {
      return this.buildTrigger("no_ready_tasks", "high", "No ready tasks and blocked items exist — unblock needed", [
        ...ctx.blockedTaskIds,
      ]);
    }

    const storyCompletion = ctx.recentCompletions.find((c) => c.type === "story");
    if (storyCompletion) {
      return this.buildTrigger("story_completed", "high", `Story ${storyCompletion.id} completed — assess outcomes`, [
        storyCompletion.id,
      ]);
    }

    if (ctx.blockedTaskIds.length > 0) {
      return this.buildTrigger("task_blocked", "standard", `Task ${ctx.blockedTaskIds[0]} is blocked`, [
        ctx.blockedTaskIds[0]!,
      ]);
    }

    if (ctx.tasksSinceBrainstorm >= this.config.tasksPerBrainstorm) {
      return this.buildTrigger(
        "tasks_completed",
        "standard",
        `${ctx.tasksSinceBrainstorm} tasks completed since last brainstorm — routine check`,
      );
    }

    return null;
  }

  async execute(trigger: BrainstormTrigger, projectContext: string): Promise<BrainstormOutput> {
    switch (trigger.level) {
      case "standard":
        return this.executeStandard(trigger, projectContext);
      case "high":
        return this.executeHigh(trigger, projectContext);
      case "deep":
        return this.executeDeep(trigger, projectContext);
      default: {
        const _exhaustive: never = trigger.level;
        throw new Error(`Unknown brainstorm level: ${String(_exhaustive)}`);
      }
    }
  }

  private async executeStandard(trigger: BrainstormTrigger, projectContext: string): Promise<BrainstormOutput> {
    const prompt = this.buildPrompt("single-agent", trigger, projectContext, [
      "You are a planning agent. Analyze the current project state and recommend next actions.",
    ]);

    const parsed = await this.llm.generateStructured(prompt, BrainstormResponseSchema);

    return {
      level: "standard",
      recommendations: parsed.recommendations,
      reasoning: parsed.reasoning,
    };
  }

  private async executeHigh(trigger: BrainstormTrigger, projectContext: string): Promise<BrainstormOutput> {
    const proposerPrompt = this.buildPrompt("proposer", trigger, projectContext, [
      "You are the Proposer. Analyze the situation and propose concrete actions to move the project forward.",
      "Be specific about what should be created, changed, or investigated.",
    ]);

    const skepticPrompt = this.buildPrompt("skeptic", trigger, projectContext, [
      "You are the Skeptic. Challenge the proposed actions.",
      "Identify risks, missing considerations, and alternative approaches.",
      "Be constructively critical — the goal is better decisions, not blocking progress.",
    ]);

    const [proposerParsed, skepticParsed] = await Promise.all([
      this.llm.generateStructured(proposerPrompt, BrainstormResponseSchema),
      this.llm.generateStructured(skepticPrompt, BrainstormResponseSchema),
    ]);

    return {
      level: "high",
      recommendations: proposerParsed.recommendations,
      reasoning: proposerParsed.reasoning,
      dissent: skepticParsed.dissent ?? skepticParsed.reasoning,
    };
  }

  private async executeDeep(trigger: BrainstormTrigger, projectContext: string): Promise<BrainstormOutput> {
    const perspectives = [
      {
        role: "architecture",
        instructions: [
          "You are the Architecture expert. Evaluate structural implications.",
          "Consider modularity, boundaries, coupling, and long-term maintainability.",
        ],
      },
      {
        role: "risk",
        instructions: [
          "You are the Risk analyst. Identify threats and failure modes.",
          "Consider technical debt, resource constraints, and external dependencies.",
        ],
      },
      {
        role: "implementation",
        instructions: [
          "You are the Implementation specialist. Focus on execution feasibility.",
          "Consider effort estimates, dependencies, and incremental delivery strategy.",
        ],
      },
      {
        role: "delivery",
        instructions: [
          "You are the Delivery lead. Focus on user value and shipping velocity.",
          "Consider what ships fastest, what users need most, and what can be deferred.",
        ],
      },
    ] as const;

    const expertPromises = perspectives.map((p) =>
      this.llm.generateStructured(
        this.buildPrompt(p.role, trigger, projectContext, [...p.instructions]),
        BrainstormResponseSchema,
      ),
    );

    const parsedResponses = await Promise.all(expertPromises);

    const allRecommendations = parsedResponses.flatMap((p) => p.recommendations);
    const combinedReasoning = perspectives
      .map((p, i) => `[${p.role}] ${parsedResponses[i]!.reasoning}`)
      .join("\n\n");
    const combinedDissent = parsedResponses
      .map((p) => p.dissent)
      .filter((d): d is string => d !== undefined)
      .join("\n");

    return {
      level: "deep",
      recommendations: this.deduplicateRecommendations(allRecommendations),
      reasoning: combinedReasoning,
      dissent: combinedDissent || undefined,
    };
  }

  private buildPrompt(role: string, trigger: BrainstormTrigger, projectContext: string, instructions: string[]): string {
    const parts: string[] = [
      `# Brainstorm: ${role}`,
      "",
      "## Instructions",
      ...instructions,
      "",
      "## Trigger",
      `Reason: ${trigger.reason}`,
      `Context: ${trigger.context}`,
    ];

    if (trigger.relatedItemIds && trigger.relatedItemIds.length > 0) {
      parts.push(`Related items: ${trigger.relatedItemIds.join(", ")}`);
    }

    parts.push(
      "",
      "## Scope Guardrails",
      "- Only suggest work items that directly advance the project vision described below",
      "- Each recommendation MUST include a rationale explaining how it connects to the vision",
      "- Do NOT suggest features not described or implied by the vision",
      "- Do NOT duplicate existing work items listed in the Project Context",
      "- Maximum 3 recommendations",
    );

    parts.push("", "## Project Context", projectContext);
    parts.push(
      "",
      "## Response Format",
      "Respond with JSON: { recommendations: [...], reasoning: string, dissent?: string }",
      'Each recommendation: { action, title, description, priority, rationale, relatedTo?, dependsOn? }',
      "For create_task/create_story/create_feature recommendations:",
      "- relatedTo: the id of the existing work item the new item belongs under (its parent)",
      "- dependsOn: ids of existing work items that must complete before the new item can start",
      "- relatedTo and dependsOn MUST be ids copied verbatim from the Project Context — never invent ids and never use titles",
    );

    return parts.join("\n");
  }

  private deduplicateRecommendations(recs: Recommendation[]): Recommendation[] {
    const seen = new Set<string>();
    const result: Recommendation[] = [];
    for (const rec of recs) {
      const key = `${rec.action}:${rec.title}`;
      if (!seen.has(key)) {
        seen.add(key);
        result.push(rec);
      }
    }
    return result;
  }

  private buildTrigger(
    reason: TriggerReason,
    level: BrainstormLevel,
    context: string,
    relatedItemIds?: string[],
  ): BrainstormTrigger {
    return { reason, level, context, relatedItemIds };
  }
}
